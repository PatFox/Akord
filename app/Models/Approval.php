<?php

namespace App\Models;

use Database\Factories\ApprovalFactory;
use Illuminate\Database\Eloquent\Attributes\Fillable;
use Illuminate\Database\Eloquent\Attributes\Scope;
use Illuminate\Database\Eloquent\Builder;
use Illuminate\Database\Eloquent\Factories\HasFactory;
use Illuminate\Database\Eloquent\Model;
use Illuminate\Database\Eloquent\Relations\BelongsTo;
use Illuminate\Support\Carbon;

/**
 * A party's approval of one step revision. It counts while not withdrawn and while
 * its revision's content hash matches the step's current revision.
 *
 * @property int $id
 * @property int $step_id
 * @property int $step_revision_id
 * @property int $party_id
 * @property int|null $user_id
 * @property Carbon|null $withdrawn_at
 * @property bool|null $active Generated by the database: true while not withdrawn, otherwise null.
 * @property Carbon|null $created_at
 * @property Carbon|null $updated_at
 */
#[Fillable(['step_id', 'step_revision_id', 'party_id', 'user_id', 'withdrawn_at'])]
class Approval extends Model
{
    /** @use HasFactory<ApprovalFactory> */
    use HasFactory;

    /**
     * @return array<string, string>
     */
    protected function casts(): array
    {
        return [
            'withdrawn_at' => 'datetime',
        ];
    }

    /**
     * @param  Builder<self>  $query
     */
    #[Scope]
    protected function active(Builder $query): void
    {
        $query->whereNull('withdrawn_at');
    }

    /**
     * @return BelongsTo<Step, $this>
     */
    public function step(): BelongsTo
    {
        return $this->belongsTo(Step::class);
    }

    /**
     * @return BelongsTo<StepRevision, $this>
     */
    public function revision(): BelongsTo
    {
        return $this->belongsTo(StepRevision::class, 'step_revision_id');
    }

    /**
     * @return BelongsTo<Party, $this>
     */
    public function party(): BelongsTo
    {
        return $this->belongsTo(Party::class);
    }

    /**
     * The person who clicked approve; null for agents.
     *
     * @return BelongsTo<User, $this>
     */
    public function user(): BelongsTo
    {
        return $this->belongsTo(User::class);
    }
}
