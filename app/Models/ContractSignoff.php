<?php

namespace App\Models;

use Database\Factories\ContractSignoffFactory;
use Illuminate\Database\Eloquent\Attributes\Fillable;
use Illuminate\Database\Eloquent\Attributes\Scope;
use Illuminate\Database\Eloquent\Builder;
use Illuminate\Database\Eloquent\Factories\HasFactory;
use Illuminate\Database\Eloquent\Model;
use Illuminate\Database\Eloquent\Relations\BelongsTo;
use Illuminate\Support\Carbon;

/**
 * A required party's sign-off on the contract as it stood at `fingerprint`.
 *
 * @property int $id
 * @property int $contract_id
 * @property int $party_id
 * @property int|null $user_id
 * @property string $fingerprint
 * @property Carbon|null $withdrawn_at
 * @property bool|null $active Generated by the database: true while not withdrawn, otherwise null.
 * @property Carbon|null $created_at
 * @property Carbon|null $updated_at
 */
#[Fillable(['contract_id', 'party_id', 'user_id', 'fingerprint', 'withdrawn_at'])]
class ContractSignoff extends Model
{
    /** @use HasFactory<ContractSignoffFactory> */
    use HasFactory;

    /**
     * @return array<string, string>
     */
    protected function casts(): array
    {
        return [
            'withdrawn_at' => 'datetime',
        ];
    }

    /**
     * @param  Builder<self>  $query
     */
    #[Scope]
    protected function active(Builder $query): void
    {
        $query->whereNull('withdrawn_at');
    }

    /**
     * @return BelongsTo<Contract, $this>
     */
    public function contract(): BelongsTo
    {
        return $this->belongsTo(Contract::class);
    }

    /**
     * @return BelongsTo<Party, $this>
     */
    public function party(): BelongsTo
    {
        return $this->belongsTo(Party::class);
    }

    /**
     * The person who signed off; null for agents.
     *
     * @return BelongsTo<User, $this>
     */
    public function user(): BelongsTo
    {
        return $this->belongsTo(User::class);
    }
}
